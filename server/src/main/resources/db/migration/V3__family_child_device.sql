-- S06: family, parent PIN, child profile, pair codes, and devices.
-- issued_through is created here and stays null until S14.
-- Course, assignment, and sync tables are later versions.

CREATE TABLE family_account (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    auth_generation INTEGER NOT NULL DEFAULT 1,
    bootstrap_consumed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_family_auth_generation CHECK (auth_generation >= 1)
);

CREATE UNIQUE INDEX uq_family_account_singleton ON family_account ((true));

CREATE TABLE parent_credential (
    family_id BIGINT PRIMARY KEY REFERENCES family_account (id),
    pin_hash TEXT NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_parent_pin_hash_argon2id CHECK (pin_hash LIKE '$argon2id$%')
);

CREATE TABLE pin_attempt (
    family_id BIGINT NOT NULL REFERENCES family_account (id),
    device_id UUID NOT NULL,
    failed_count INTEGER NOT NULL DEFAULT 0,
    locked_until TIMESTAMPTZ,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (family_id, device_id),
    CONSTRAINT ck_pin_attempt_failed_count CHECK (failed_count >= 0)
);

CREATE TABLE parent_session (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    family_id BIGINT NOT NULL REFERENCES family_account (id),
    device_id UUID,
    token_hash VARCHAR(64) NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_parent_session_token_hash UNIQUE (token_hash),
    CONSTRAINT ck_parent_session_token_hash CHECK (token_hash ~ '^[0-9a-f]{64}$')
);

CREATE INDEX ix_parent_session_device ON parent_session (device_id);

CREATE TABLE request_idempotency (
    scope VARCHAR(32) NOT NULL,
    idempotency_key VARCHAR(128) NOT NULL,
    family_id BIGINT NOT NULL REFERENCES family_account (id),
    request_hash TEXT NOT NULL,
    resource_id BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (scope, idempotency_key)
);

CREATE TABLE child_profile (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    family_id BIGINT NOT NULL REFERENCES family_account (id),
    nickname VARCHAR(20) NOT NULL,
    age_band VARCHAR(16) NOT NULL,
    daily_minutes INTEGER NOT NULL DEFAULT 15,
    timezone_id VARCHAR(64) NOT NULL DEFAULT 'Asia/Shanghai',
    timezone_version INTEGER NOT NULL DEFAULT 1,
    profile_version INTEGER NOT NULL DEFAULT 1,
    pending_timezone VARCHAR(64),
    pending_timezone_effective_at TIMESTAMPTZ,
    issued_through DATE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_child_nickname CHECK (char_length(nickname) BETWEEN 1 AND 20),
    CONSTRAINT ck_child_age_band CHECK (age_band IN ('AGE_5', 'AGE_6', 'AGE_7')),
    CONSTRAINT ck_child_daily_minutes CHECK (daily_minutes BETWEEN 10 AND 30),
    CONSTRAINT ck_child_timezone_version CHECK (timezone_version >= 1),
    CONSTRAINT ck_child_profile_version CHECK (profile_version >= 1)
);

CREATE INDEX ix_child_profile_family ON child_profile (family_id);

CREATE TABLE pair_code (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    family_id BIGINT NOT NULL REFERENCES family_account (id),
    code_hash VARCHAR(64) NOT NULL,
    device_name VARCHAR(40),
    expires_at TIMESTAMPTZ NOT NULL,
    consumed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_pair_code_hash UNIQUE (code_hash),
    CONSTRAINT ck_pair_code_hash CHECK (code_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_pair_code_device_name CHECK (
        device_name IS NULL OR char_length(device_name) BETWEEN 1 AND 40
    )
);

CREATE TABLE pair_code_child (
    pair_code_id BIGINT NOT NULL REFERENCES pair_code (id),
    child_id BIGINT NOT NULL REFERENCES child_profile (id),
    PRIMARY KEY (pair_code_id, child_id)
);

CREATE TABLE client_device (
    device_id UUID PRIMARY KEY,
    family_id BIGINT NOT NULL REFERENCES family_account (id),
    platform VARCHAR(16) NOT NULL,
    display_name VARCHAR(40),
    token_hash VARCHAR(64) NOT NULL,
    revoked BOOLEAN NOT NULL DEFAULT FALSE,
    revoked_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_client_device_token_hash UNIQUE (token_hash),
    CONSTRAINT ck_client_device_platform CHECK (platform IN ('ANDROID', 'H5')),
    CONSTRAINT ck_client_device_token_hash CHECK (token_hash ~ '^[0-9a-f]{64}$')
);

CREATE INDEX ix_client_device_family ON client_device (family_id);

CREATE TABLE device_child_binding (
    device_id UUID NOT NULL REFERENCES client_device (device_id),
    child_id BIGINT NOT NULL REFERENCES child_profile (id),
    PRIMARY KEY (device_id, child_id)
);
